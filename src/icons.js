export function icon(name, size = 16) {
  if (name === 'github') {
    return '<svg class="icon" width="' + size + '" height="' + size + '" viewBox="0 0 16 16" fill="currentColor" aria-hidden="true">' + GITHUB_MARK + '</svg>';
  }
  if (name === 'nexus') {
    return '<svg class="icon icon--nexus" width="' + size + '" height="' + size + '" viewBox="0 0 221 221" aria-hidden="true">' + NEXUS_MARK + '</svg>';
  }
  const body = PATHS[name] || '';
  return (
    '<svg class="icon" width="' +
    size +
    '" height="' +
    size +
    '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
    body +
    '</svg>'
  );
}

export function initIcons(root = document) {
  Array.prototype.forEach.call(root.querySelectorAll('[data-icon]'), (el) => {
    if (el.querySelector('svg.icon')) {
      return;
    }
    el.insertAdjacentHTML('afterbegin', icon(el.getAttribute('data-icon')));
  });
}
